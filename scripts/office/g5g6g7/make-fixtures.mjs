// Deterministic generator for the G7 synthetic fixtures (UNI-1376 / G7-01 item A).
//
//   node scripts/office/g5g6g7/make-fixtures.mjs           write fixtures, oracle sidecars and manifest.json
//   node scripts/office/g5g6g7/make-fixtures.mjs --check   regenerate in memory, exit 1 on any drift from disk
//   node scripts/office/g5g6g7/make-fixtures.mjs --list    print "<sha256>  <path>" per fixture and oracle sidecar
//
// No clock, no randomness, no compressor: the same inputs always yield the same bytes.

