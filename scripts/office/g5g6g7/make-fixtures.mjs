// Fixture bytes are hashed in the manifest, so no checkout may normalise their line endings.
const ATTRIBUTES_PATH = `${FIXTURE_DIR}/.gitattributes`;
const ATTRIBUTES_TEXT = '# Generated by make-fixtures.mjs. Hashes in manifest.json cover the exact bytes.\n* -text\n';

const sha256 = (bytes) => crypto.createHash('sha256').update(bytes).digest('hex');
const jsonText = (value) => `${JSON.stringify(value, null, 2)}\n`;

/** Builds every fixture in memory: [{spec, bytes, sha256, path, oraclePath, oracleSha256, oracleText}] plus the manifest text. */
export function generateAll() {
  const fixtures = SPECS.map((spec) => {
    const { bytes, oracle } = spec.build();
    const digest = sha256(bytes);
    const filePath = `${FIXTURE_DIR}/${spec.file}`;
    const oraclePath = `${FIXTURE_DIR}/${spec.id}.oracle.json`;
    const oracleText = jsonText({ fixtureId: spec.id, format: spec.format, fixtureSha256: digest, synthetic: true, ...oracle });
    return {
      spec,
      bytes,
      sha256: digest,
      path: filePath,
      oraclePath,
      // The sidecar is hashed too: AC-3's listing must cover every committed
      // file the manifest names, not only the fixture bytes.
      oracleSha256: sha256(Buffer.from(oracleText, 'utf8')),
      oracleText,
    };
  });
  const manifest = {
    schemaVersion: 1,
    kind: 'uniwork-office-g5g6g7-fixtures',
    fixtures: fixtures.map((f) => ({
      id: f.spec.id,
      path: f.path,
      format: f.spec.format,
      sha256: f.sha256,
      bytes: f.bytes.length,
      synthetic: true,
      description: f.spec.description,
      features: f.spec.features,
      oracle: f.oraclePath,
      oracleSha256: f.oracleSha256,
    })),
  };
  return { fixtures, manifestText: jsonText(manifest) };
}

const abs = (rel) => path.join(repoRoot, rel);

function write({ fixtures, manifestText }) {
  fs.mkdirSync(abs(FIXTURE_DIR), { recursive: true });
  for (const f of fixtures) {
    fs.writeFileSync(abs(f.path), f.bytes);
    fs.writeFileSync(abs(f.oraclePath), f.oracleText);
  }
  fs.writeFileSync(abs(MANIFEST_PATH), manifestText);
  fs.writeFileSync(abs(ATTRIBUTES_PATH), ATTRIBUTES_TEXT);
}

/** Returns the list of drift messages; empty means disk == generator output. */
export function checkDisk({ fixtures, manifestText }) {
  const problems = [];
  const expected = new Map([
    [MANIFEST_PATH, Buffer.from(manifestText)],
    [ATTRIBUTES_PATH, Buffer.from(ATTRIBUTES_TEXT)],
  ]);
  for (const f of fixtures) {
    expected.set(f.path, f.bytes);
    expected.set(f.oraclePath, Buffer.from(f.oracleText));
  }
  for (const [rel, bytes] of expected) {
    if (!fs.existsSync(abs(rel))) problems.push(`missing: ${rel}`);
    else if (!fs.readFileSync(abs(rel)).equals(bytes)) problems.push(`drift: ${rel} (disk sha256 ${sha256(fs.readFileSync(abs(rel)))}, generated ${sha256(bytes)})`);
  }
  if (fs.existsSync(abs(FIXTURE_DIR))) {
    for (const name of fs.readdirSync(abs(FIXTURE_DIR))) {
      if (!expected.has(`${FIXTURE_DIR}/${name}`)) problems.push(`unexpected file: ${FIXTURE_DIR}/${name}`);
    }
  }
  return problems;
}

function main(argv) {
  const mode = argv.includes('--check') ? 'check' : argv.includes('--list') ? 'list' : 'write';
  const generated = generateAll();
  if (mode === 'list') {
    // sha256sum order: every fixture and its oracle sidecar, "<hash>  <path>".
    for (const f of generated.fixtures) {
      process.stdout.write(`${f.sha256}  ${f.path}\n`);
      process.stdout.write(`${f.oracleSha256}  ${f.oraclePath}\n`);
    }
    return 0;
  }
  if (mode === 'check') {
    const problems = checkDisk(generated);
    if (problems.length) {
      for (const p of problems) process.stderr.write(`${p}\n`);
      process.stderr.write('make-fixtures --check: FAIL (run without --check to regenerate, then review the diff)\n');
      return 1;
    }
    process.stdout.write(`make-fixtures --check: OK (${generated.fixtures.length} fixtures, bytes and hashes match)\n`);
    return 0;
  }
  write(generated);
  process.stdout.write(`wrote ${generated.fixtures.length} fixtures, ${generated.fixtures.length} oracles and ${MANIFEST_PATH}\n`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exitCode = main(process.argv.slice(2));
}
