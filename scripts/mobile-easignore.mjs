#!/usr/bin/env node
// Writes the repo-root .easignore from every .gitignore git tracks, plus the
// few paths only EAS must skip. EAS Build packs the upload archive with
// .easignore *instead of* the .gitignore files (https://expo.fyi/eas-build-archive),
// so a pattern added to a .gitignore and not here ships what git never holds:
// a code-signing private key, a local .env, a live socket the archive cannot
// copy (PR #387). Kept by hand it had already drifted (the OTA signing keys
// were missing); generated, it cannot.
//
//   node scripts/mobile-easignore.mjs           rewrite .easignore
//   node scripts/mobile-easignore.mjs --check   exit 1 when .easignore is stale
//
// scripts/mobile-easignore.test.mjs runs --check's comparison and proves the
// result with git's own matcher.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const root = path.resolve(import.meta.dirname, "..");
export const EASIGNORE = path.join(root, ".easignore");

// Paths EAS must skip that no tracked .gitignore names, each with its reason.
const EAS_ONLY = [
  {
    reason: "the CodeGraph index (its .gitignore keeps itself in git) holds a live daemon socket the archive cannot copy.",
    patterns: [".codegraph/"],
  },
];

/**
 * A pattern of the .gitignore in `dir` (repo-relative, "" for the root),
 * rewritten for a file at the repo root with git's rules: a leading or middle
 * slash anchors it to `dir`; without one it matches at any depth below `dir`.
 * Blank lines and comments come back unchanged.
 */
export function rebase(line, dir) {
  const pattern = line.replace(/(?<!\\)\s+$/, "");
  if (dir === "" || pattern === "" || pattern.startsWith("#")) return pattern;
  if (pattern.startsWith("!")) return `!${rebase(pattern.slice(1), dir)}`;
  // A leading "\#" or "\!" escapes a first character that is no longer first once the folder leads.
  const body = /^\\[#!]/.test(pattern) ? pattern.slice(1) : pattern;
  if (body.startsWith("/")) return `${dir}${body}`;
  if (body.replace(/\/$/, "").includes("/")) return `${dir}/${body}`;
  return `${dir}/**/${body}`;
}

/** The tracked .gitignore files, the root's first, then by path (deeper ones override, as in git). */
export function trackedGitignores() {
  const out = execFileSync("git", ["ls-files", "-z"], { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
  return out
    .split("\0")
    .filter((file) => path.posix.basename(file) === ".gitignore")
    .sort((a, b) => (a === ".gitignore" ? -1 : b === ".gitignore" ? 1 : a.localeCompare(b)));
}

/** The .easignore text for these .gitignore files (repo-relative) and their contents. */
export function render(files, read = (file) => fs.readFileSync(path.join(root, file), "utf8")) {
  const lines = [
    "# GENERATED by scripts/mobile-easignore.mjs from every tracked .gitignore: do not edit.",
    "# EAS reads this instead of the .gitignore files (https://expo.fyi/eas-build-archive);",
    "# change a .gitignore (or EAS_ONLY in the script) and run the script again.",
  ];
  for (const file of files) {
    const dir = path.posix.dirname(file) === "." ? "" : path.posix.dirname(file);
    lines.push("", `# --- ${file}`);
    lines.push(...read(file).replace(/\n+$/, "").split("\n").map((line) => rebase(line, dir)));
  }
  for (const { reason, patterns } of EAS_ONLY) lines.push("", `# --- EAS only: ${reason}`, ...patterns);
  return `${lines.join("\n")}\n`;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const want = render(trackedGitignores());
  if (process.argv.includes("--check")) {
    const have = fs.existsSync(EASIGNORE) ? fs.readFileSync(EASIGNORE, "utf8") : "";
    if (have !== want) {
      console.error(".easignore is stale: run node scripts/mobile-easignore.mjs");
      process.exit(1);
    }
    console.log(".easignore matches the .gitignore files");
  } else {
    fs.writeFileSync(EASIGNORE, want);
    console.log(`wrote ${path.relative(root, EASIGNORE)}`);
  }
}
