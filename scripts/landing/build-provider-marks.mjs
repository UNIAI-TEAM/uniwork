/**
 * Vendors the model-provider marks the trust band renders.
 *
 * The band names three providers UniWork actually calls
 * (server/internal/ai/provider/). It used to set them as plain text, on the
 * reasoning that a mark nobody owns cannot go stale. The counter-argument won:
 * two of the three are wordmarks a Vietnamese reader has no reason to
 * recognise as software, and a row of set type is the one place on this page
 * where a claim about infrastructure looks like a claim about nothing.
 *
 * The artwork is NOT redrawn here and must never be. It is copied verbatim
 * from @lobehub/icons-static-svg, a devDependency, into a generated module, so
 * production imports committed data and no runtime dependency is added for
 * three glyphs. Each source is single-path, 24x24 and painted with
 * `currentColor`, which is why the band needs no new colour token to work in
 * both themes.
 *
 * The marks remain the trademarks of their owners. The package's MIT licence
 * covers the files, not the brands; this is nominative use — naming the model
 * hosts a customer can pick — and nothing here restyles a mark or implies an
 * endorsement.
 *
 * Run `pnpm landing:marks` after bumping the package.
 * scripts/landing-marks.test.mjs fails if the committed module and the lock
 * stop agreeing.
 */
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const require = createRequire(path.join(root, "package.json"));

const pkgJson = require("@lobehub/icons-static-svg/package.json");
const iconsDir = path.join(path.dirname(require.resolve("@lobehub/icons-static-svg/package.json")), "icons");

/** Slug in the package -> the key the trust band asks for. */
const MARKS = {
  anthropic: "Anthropic",
  openai: "OpenAI",
  ollama: "Ollama",
};

const outModule = path.join(root, "apps", "web", "features", "landing", "provider-marks.generated.ts");
const outLock = path.join(root, "scripts", "landing", "marks.lock.json");

const sha = (s) => createHash("sha256").update(s).digest("hex");

/** One path, one viewBox. Anything else means the upstream artwork changed shape. */
function extract(slug, svg) {
  const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1];
  const paths = [...svg.matchAll(/<path\b[^>]*\bd="([^"]+)"/g)].map((m) => m[1]);
  if (!viewBox) throw new Error(`${slug}: no viewBox`);
  if (paths.length !== 1) throw new Error(`${slug}: expected 1 path, found ${paths.length}`);
  if (!/fill="currentColor"/.test(svg)) throw new Error(`${slug}: artwork is not currentColor`);
  return { viewBox, path: paths[0] };
}

const marks = {};
const lock = { _: "Generated by scripts/landing/build-provider-marks.mjs. Run `pnpm landing:marks`.", package: `${pkgJson.name}@${pkgJson.version}`, license: pkgJson.license, marks: {} };

for (const [slug, title] of Object.entries(MARKS)) {
  const file = path.join(iconsDir, `${slug}.svg`);
  const svg = fs.readFileSync(file, "utf8");
  const art = extract(slug, svg);
  marks[slug] = { title, ...art };
  lock.marks[slug] = { title, source: `icons/${slug}.svg`, source_sha256: sha(svg), path_sha256: sha(art.path), viewBox: art.viewBox };
}

const body = `// Generated by scripts/landing/build-provider-marks.mjs. Do not edit.
// Run \`pnpm landing:marks\` to regenerate.
//
// Artwork copied verbatim from ${lock.package} (${lock.license}). Each mark is
// a single path on a ${marks.anthropic.viewBox} grid, painted with currentColor by the
// consumer. The marks are the trademarks of their respective owners and are
// used to name the model hosts UniWork can call; see the generator's header.

export type ProviderMark = {
  readonly title: string;
  readonly viewBox: string;
  readonly path: string;
};

export const PROVIDER_MARKS = {
${Object.entries(marks)
  .map(([slug, m]) => `  ${slug}: {\n    title: ${JSON.stringify(m.title)},\n    viewBox: ${JSON.stringify(m.viewBox)},\n    path: ${JSON.stringify(m.path)},\n  },`)
  .join("\n")}
} as const satisfies Record<string, ProviderMark>;

export type ProviderMarkKey = keyof typeof PROVIDER_MARKS;
`;

fs.writeFileSync(outModule, body);
fs.writeFileSync(outLock, `${JSON.stringify(lock, null, 2)}\n`);
console.log(`wrote ${path.relative(root, outModule)} and ${path.relative(root, outLock)} from ${lock.package}`);
