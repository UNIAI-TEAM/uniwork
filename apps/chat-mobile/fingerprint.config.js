// @expo/fingerprint's settings for `runtimeVersion: { policy: "fingerprint" }`
// (app.config.ts). The fingerprint decides which binaries an update may land
// on, so it must hash what the native app is made of and nothing else.
//
// `extra` is left out: it holds the server URLs, the Sentry DSN and the EAS
// project id, which JavaScript reads at run time from the update's own
// manifest. Hashing them would split one native build into a runtime per
// environment value, and an update published from CI (where a value can be
// missing or rotated) would silently match no phone. The publishing workflow
// checks those values instead (.github/workflows/chat-mobile-update.yml).
const { SourceSkips } = require("expo/fingerprint");

/** @type {import("expo/fingerprint").Config} */
module.exports = {
  // Replaces the default skip set, so the default (package.json scripts that
  // run no native step) is kept beside it.
  sourceSkips: SourceSkips.PackageJsonAndroidAndIosScriptsIfNotContainRun | SourceSkips.ExpoConfigExtraSection,
  // The local modules' JVM unit tests (Robolectric, mobile-verify › android-release) and
  // instrumented tests (src/androidTest, run on android-smoke's emulator from their own APK)
  // never reach a binary: adding or changing one must not split the runtime.
  //
  // android/ and ios/ are generated by prebuild (CNG, both gitignored): fingerprint skips them
  // by itself when it can tell the project is managed, but on the EAS builder, after the
  // PREBUILD phase, it hashed android/ as a bare native dir and the build stopped on a runtime
  // mismatch with the fingerprint eas-cli computed here. They are named so both sides agree.
  //
  // eas-environment-secrets/ holds EAS file variables (GOOGLE_SERVICES_JSON, the Firebase
  // config behind android.googleServicesFile). Only the builder has the file, so hashing it
  // made every EAS fingerprint differ from the local and CI one; a new Firebase config ships
  // with a version bump anyway. The leading **/ lets the pattern match the ../ path.
  ignorePaths: [
    "modules/*/android/src/test/**",
    "modules/*/android/src/androidTest/**",
    "android/**/*",
    "ios/**/*",
    "**/eas-environment-secrets/**",
  ],
};
