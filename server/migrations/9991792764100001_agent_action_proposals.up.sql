-- Ask UNI write proposals live on the server (ADR 0044): the model proposes, a
-- person (or a mode the person chose) applies. No foreign keys by repo rule.
CREATE TABLE IF NOT EXISTS agent_action_proposals (
  id TEXT PRIMARY KEY,
  organization_id TEXT NOT NULL,
  workspace_id TEXT NOT NULL,
  source TEXT NOT NULL CHECK (source IN ('ask_uni', 'agent_run')),
  run_id TEXT NOT NULL,
  agent_id TEXT,
  conversation_id TEXT,
  message_id TEXT,
  position INTEGER NOT NULL,
  action_type TEXT NOT NULL,
  target_kind TEXT NOT NULL,
  target_id TEXT,
  payload TEXT NOT NULL,
  preview TEXT NOT NULL,
  risk_level TEXT NOT NULL CHECK (risk_level IN ('l1', 'l2', 'l3')),
  mode TEXT NOT NULL CHECK (mode IN ('ask', 'plan', 'auto')),
  tainted BOOLEAN NOT NULL DEFAULT false,
  target_revision BIGINT,
  status TEXT NOT NULL CHECK (status IN ('pending', 'applying', 'applied', 'rejected', 'failed', 'undoing', 'undone')),
  decision TEXT CHECK (decision IN ('confirmed', 'plan', 'auto', 'answer')),
  result TEXT NOT NULL DEFAULT '{}',
  undo TEXT,
  error TEXT,
  decided_by TEXT,
  decided_at TIMESTAMPTZ,
  applied_at TIMESTAMPTZ,
  undone_by TEXT,
  undone_at TIMESTAMPTZ,
  expires_at TIMESTAMPTZ NOT NULL,
  created_by TEXT NOT NULL,
  created_by_kind TEXT NOT NULL CHECK (created_by_kind IN ('human', 'agent', 'system')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
